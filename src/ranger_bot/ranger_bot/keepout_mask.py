"""Build a Nav2 keepout mask that fences off the rocks in nature_reserve.wbt.

Many Webots Rock objects are lower than the LDS-01 scan plane (0.173 m): the "regular"
mesh is only ~0.05 m tall per unit of scale, so lidar, SLAM and the costmaps never see
them, and the robot drove onto lake rock 3 and tipped over. They are known terrain
hazards, so they go into a mask that a static "rock_layer" adds to both Nav2 costmaps
(before inflation, so the zones are inflated by the robot size like any obstacle).
The mask is "unknown" (205) everywhere except the rocks (0 = occupied), so merging it
with use_maximum never overwrites the SLAM map. It uses exactly the SLAM map's grid
(origin, size, resolution): a static layer resizes the costmap to its own map, and two
static layers with different grids keep resizing it, which wipes both (everything read
"free"). Map frame == Webots world frame, because mapping starts at the origin.

    ros2 run ranger_bot keepout_mask        # rewrites maps/keepout.{pgm,yaml} to match maps/reserve
mapping_tour runs this automatically after saving a new map.
"""

import argparse
import math
import os
import re

# Rock.proto mesh extents (R2025a): max horizontal radius and max z of the vertices at scale 1.
# The rock is centred at its translation, so the part above ground is max_z * scale.
ROCK_EXTENT = {
    'regular': {'radius': 0.0836, 'height': 0.0494},
    'flat': {'radius': 0.2281, 'height': 0.1759},
}
LIDAR_HEIGHT = 0.173


def parse_rocks(world_text):
    """Return [(name, x, y, radius, height)] for every Rock node in a .wbt file."""
    rocks = []
    for block in re.findall(r'^Rock\s*\{(.*?)^\}', world_text, flags=re.S | re.M):
        t = re.search(r'translation\s+(\S+)\s+(\S+)', block)
        if t is None:
            continue
        name = re.search(r'name\s+"([^"]*)"', block)
        kind = re.search(r'type\s+"([^"]*)"', block)
        scale = re.search(r'scale\s+(\S+)', block)
        ext = ROCK_EXTENT[kind.group(1) if kind else 'regular']
        s = float(scale.group(1)) if scale else 1.0
        rocks.append((name.group(1) if name else 'rock', float(t.group(1)), float(t.group(2)),
                      ext['radius'] * s, ext['height'] * s))
    return rocks


def read_map_grid(map_yaml):
    """(origin_x, origin_y, resolution, width, height) of a map_server map (yaml + pgm)."""
    with open(map_yaml) as f:
        text = f.read()
    image = re.search(r'^image:\s*(\S+)', text, re.M).group(1)
    resolution = float(re.search(r'^resolution:\s*(\S+)', text, re.M).group(1))
    ox, oy = (float(v) for v in
              re.search(r'^origin:\s*\[\s*([^,\s]+)\s*,\s*([^,\s]+)', text, re.M).groups())
    with open(os.path.join(os.path.dirname(map_yaml), image), 'rb') as f:
        header = f.read(64).split()           # P5 <width> <height> <maxval>
    return ox, oy, resolution, int(header[1]), int(header[2])


def render_mask(rocks, clearance, grid):
    """Mask on `grid` = (origin_x, origin_y, resolution, width, height); returns pixel rows.

    0 = rock (occupied), 205 = unknown, i.e. "no information" for the costmap merge.
    """
    ox, oy, res, w, h = grid
    rows = [[205] * w for _ in range(h)]
    for _, x, y, radius, _ in rocks:
        r = radius + clearance
        for j in range(h):
            cy = oy + (h - 1 - j + 0.5) * res        # image row 0 is the top (max y)
            if abs(cy - y) > r:
                continue
            for i in range(w):
                cx = ox + (i + 0.5) * res
                if math.hypot(cx - x, cy - y) <= r:
                    rows[j][i] = 0
    return rows


def write_mask(rows, grid, path_base):
    ox, oy, res, w, h = grid
    with open(path_base + '.pgm', 'wb') as f:
        f.write(f'P5\n{w} {h}\n255\n'.encode())
        f.write(bytes(v for row in rows for v in row))
    with open(path_base + '.yaml', 'w') as f:
        f.write('# Generated by `ros2 run ranger_bot keepout_mask` - rocks too low for the lidar\n'
                '# (0 = rock, 205 = unknown). Same grid as the SLAM map; regenerate after re-mapping.\n'
                f'image: {os.path.basename(path_base)}.pgm\nmode: trinary\n'
                f'resolution: {res}\norigin: [{ox}, {oy}, 0.0]\n'
                f'negate: 0\noccupied_thresh: 0.65\nfree_thresh: 0.196\n')


def main(args=None):
    src = os.path.expanduser('~/ranger_ws/src/ranger_bot')
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--world', default=os.path.join(src, 'worlds', 'nature_reserve.wbt'))
    p.add_argument('--map', default=os.path.join(src, 'maps', 'reserve.yaml'),
                   help='SLAM map whose grid the mask must match')
    p.add_argument('--out', default=None, help="default: 'keepout' next to the map")
    # Margin around the rock itself; the costmap inflation then adds the robot's size.
    p.add_argument('--clearance', type=float, default=0.10)
    p.add_argument('--all', action='store_true',
                   help='fence off every rock, not just the ones below the lidar plane')
    a, _ = p.parse_known_args(args)
    with open(a.world) as f:
        rocks = parse_rocks(f.read())
    chosen = [r for r in rocks if a.all or r[4] < LIDAR_HEIGHT + 0.03]
    for name, x, y, radius, height in rocks:
        tag = 'KEEPOUT' if any(c[0] == name for c in chosen) else 'lidar sees it'
        print(f'{name:14s} ({x:6.2f}, {y:6.2f})  radius {radius:.2f} m  height {height:.2f} m  {tag}')
    out = a.out or os.path.join(os.path.dirname(a.map), 'keepout')
    grid = read_map_grid(a.map)
    write_mask(render_mask(chosen, a.clearance, grid), grid, out)
    print(f'wrote {out}.pgm/.yaml ({len(chosen)} keepout zones, grid of {a.map})')


if __name__ == '__main__':
    main()
